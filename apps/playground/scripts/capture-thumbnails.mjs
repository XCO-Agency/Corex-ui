/**
 * Screenshots each registry/block example into public/thumbnails/{slug}.png
 * for the Overview grid.
 *
 * Usage (dev server must already be running):
 *   pnpm --filter playground capture:thumbnails
 *   pnpm --filter playground capture:thumbnails -- --base http://localhost:5173 --only button,tabs
 */
import { chromium } from "playwright";
import { mkdir, writeFile, readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const outDir = join(root, "public", "thumbnails");

function parseArgs(argv) {
  const args = { base: "http://localhost:5173", only: null };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--") continue;
    if (arg === "--base") args.base = argv[++i];
    else if (arg === "--only") args.only = new Set(argv[++i].split(",").map((s) => s.trim()));
  }
  return args;
}

/** Pull slug strings from category/block source without importing React modules. */
async function collectSlugs() {
  const { execSync } = await import("node:child_process");
  const output = execSync(
    `rg -o 'slug: "[^"]+"' src/data/categories src/data/blocks --no-filename`,
    { cwd: root, encoding: "utf8" },
  );
  const slugs = [
    ...new Set(
      output
        .split("\n")
        .map((line) => {
          const match = line.match(/slug: "([^"]+)"/);
          return match?.[1];
        })
        .filter(Boolean),
    ),
  ].sort();
  return slugs;
}

async function waitForReady(page, timeoutMs = 45000) {
  await page.waitForFunction(
    () => {
      const el = document.querySelector("[data-thumbnail-frame]");
      const state = el?.getAttribute("data-thumbnail-ready");
      return state === "true" || state === "missing";
    },
    { timeout: timeoutMs },
  );
  // Extra beat for web-component paint / fonts.
  await page.waitForTimeout(400);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  let slugs = await collectSlugs();
  if (args.only) slugs = slugs.filter((slug) => args.only.has(slug));

  await mkdir(outDir, { recursive: true });

  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({
    viewport: { width: 640, height: 320 },
    deviceScaleFactor: 2,
  });

  const manifest = [];
  let failed = 0;

  for (const slug of slugs) {
    const url = `${args.base.replace(/\/$/, "")}/_capture/${slug}`;
    process.stdout.write(`capturing ${slug}… `);
    try {
      await page.goto(url, { waitUntil: "networkidle", timeout: 30000 });
      await waitForReady(page);
      const frame = page.locator("[data-thumbnail-frame]");
      const ready = await frame.getAttribute("data-thumbnail-ready");
      if (ready === "missing") {
        console.log("missing entry");
        failed += 1;
        continue;
      }
      const file = join(outDir, `${slug}.png`);
      await frame.screenshot({ path: file, type: "png" });
      manifest.push(slug);
      console.log("ok");
    } catch (error) {
      failed += 1;
      console.log(`FAIL (${error instanceof Error ? error.message : error})`);
    }
  }

  await browser.close();

  // Merge with any existing PNGs so `--only` does not wipe the map.
  const { readdir } = await import("node:fs/promises");
  const onDisk = (await readdir(outDir))
    .filter((name) => name.endsWith(".png"))
    .map((name) => name.replace(/\.png$/, ""))
    .sort();
  const all = [...new Set([...onDisk, ...manifest])].sort();

  const manifestPath = join(outDir, "manifest.json");
  await writeFile(manifestPath, `${JSON.stringify(all, null, 2)}\n`);
  // Touch a tiny index so Overview can import a static map without glob hacks.
  const mapPath = join(root, "src", "data", "thumbnail-images.ts");
  const existing = await readFile(mapPath, "utf8").catch(() => "");
  const body = `/** Auto-generated by scripts/capture-thumbnails.mjs — do not edit by hand. */\nexport const thumbnailImages: Record<string, string> = {\n${all
    .map((slug) => `  "${slug}": "/thumbnails/${slug}.png",`)
    .join("\n")}\n};\n`;
  if (existing !== body) await writeFile(mapPath, body);

  console.log(`\nDone. ${manifest.length} captured this run, ${all.length} on disk, ${failed} failed → ${outDir}`);
  if (failed > 0) process.exitCode = 1;
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
